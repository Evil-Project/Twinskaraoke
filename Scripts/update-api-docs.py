# Index


def write_index(loaded: dict, rest_rows: dict, async_rows: dict) -> None:
    rest = loaded["rest"]
    schemes = rest.get("components", {}).get("securitySchemes", {})
    lines = [
        HEADER.rstrip(),
        "",
        "# Neuro & Evil Karaoke API reference (for agents and humans)",
        "",
        "Generated from the official specs at https://docs.neurokaraoke.com. Use it instead of",
        "guessing endpoints, fields or types. Start here, then open only the file for the area",
        "you work on. The raw specs in `specs/` are complete and can be queried with `jq`, e.g.",
        "`jq '.paths[\"/api/songs\"]' docs/api/specs/rest.openapi.json`.",
        "",
        "Refresh with `Scripts/update-api-docs.py` (downloads the live specs and regenerates",
        "these files). Never edit the generated Markdown by hand.",
        "",
        "## Hosts",
        "",
        "| API | Base URL | Reference |",
        "| --- | --- | --- |",
    ]
    for _, _, slug_name, kind in SOURCES:
        spec = loaded[slug_name]
        title = spec.get("info", {}).get("title")
        if kind == "openapi":
            hosts = ", ".join(s.get("url", "") for s in spec.get("servers", []))
            ref = f"`{slug_name}/`" if (OUT / slug_name).is_dir() else f"[{slug_name}.md]({slug_name}.md)"
        else:
            hosts = ", ".join(f"{s.get('protocol')}://{s.get('host')}" for s in spec.get("servers", {}).values())
            ref = f"[{slug_name}.md]({slug_name}.md)"
        lines.append(f"| {title} | {hosts} | {ref} |")
    lines += [
        "",
        "The app also uses the China mirrors (`*.neurokaraoke.com.cn`); see",
        "`Packages/Core/Configuration/Apple/StorageHost.swift`.",
        "",
        "## Authentication",
        "",
    ]
    for name, scheme in schemes.items():
        where = f"header `{scheme.get('name')}`" if scheme.get("in") == "header" else "`Authorization: Bearer <token>`"
        lines.append(f"- `{name}` — {where}. {(scheme.get('description') or '').strip()}")
    lines += [
        "",
        "In the tables, \"optional\" means the endpoint works without auth but returns more",
        "(for example the caller's own data) when authenticated.",
        "",
    ]
    for slug_name, rows in rest_rows.items():
        spec = loaded[slug_name]
        lines += [f"## {spec.get('info', {}).get('title')} — endpoints", ""]
        current = None
        for tag, method, path, summary, auth, link in rows:
            if tag != current:
                if current is not None:
                    lines.append("")
                lines += [f"### {tag}", "", "| Method | Path | Summary | Auth |", "| --- | --- | --- | --- |"]
                current = tag
            lines.append(f"| {method} | [`{path}`]({link}) | {summary} | {auth} |")
        lines.append("")
    for slug_name, rows in async_rows.items():
        spec = loaded[slug_name]
        lines += [f"## {spec.get('info', {}).get('title')} — messages", "",
                  "| Direction | Message | Summary |", "| --- | --- | --- |"]
        for direction, title, summary, link in rows:
            lines.append(f"| {direction} | [`{title}`]({link}) | {summary} |")
        lines.append("")
    (OUT / "README.md").write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")


# --------------------------------------------------------------------------


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--offline", action="store_true", help="regenerate from docs/api/specs only")
    group.add_argument("--check", action="store_true", help="exit 1 if the live specs differ from the committed ones")
    args = parser.parse_args()

    SPECS.mkdir(parents=True, exist_ok=True)
    if not args.offline:
        changed = []
        for remote, local, _, _ in SOURCES:
            text = canonical(fetch(remote))
            target = SPECS / local
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                changed.append(local)
                if not args.check:
                    target.write_text(text, encoding="utf-8")
        if args.check:
            if changed:
                print("API specs changed upstream: " + ", ".join(changed))
                print("Run Scripts/update-api-docs.py and commit the result.")
                return 1
            print("API specs are up to date.")
            return 0
        print("Changed specs: " + (", ".join(changed) if changed else "none"))

    # Regenerate everything from the committed specs.
    for old in OUT.rglob("*.md"):
        old.unlink()
    for folder in sorted((p for p in OUT.iterdir() if p.is_dir() and p != SPECS), reverse=True):
        if not any(folder.iterdir()):
            folder.rmdir()
    loaded = {slug_name: json.loads((SPECS / local).read_text(encoding="utf-8"))
              for _, local, slug_name, _ in SOURCES}
    rest_rows, async_rows = {}, {}
    for _, _, slug_name, kind in SOURCES:
        if kind == "openapi":
            rest_rows[slug_name] = write_openapi(loaded[slug_name], slug_name, slug_name)
        else:
            async_rows[slug_name] = write_asyncapi(loaded[slug_name], slug_name)
    write_index(loaded, rest_rows, async_rows)
    files = sorted(p.relative_to(ROOT).as_posix() for p in OUT.rglob("*.md"))
    print(f"Wrote {len(files)} Markdown files to docs/api/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
