#!/usr/bin/env python3
"""Download the Neuro & Evil Karaoke API specs and generate a compact
Markdown reference for humans and AI coding agents.

    Scripts/update-api-docs.py            download specs, regenerate docs/api
    Scripts/update-api-docs.py --offline  regenerate from docs/api/specs only
    Scripts/update-api-docs.py --check    exit 1 if the live specs differ
                                          from docs/api/specs

Source: https://docs.neurokaraoke.com (Scalar). The raw OpenAPI/AsyncAPI
files in docs/api/specs are the source of truth; the Markdown is generated
from them. Never edit the generated Markdown by hand.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "api"
SPECS = OUT / "specs"
BASE = "https://docs.neurokaraoke.com/"

# (remote path, local file, slug, kind)
SOURCES = [
    ("openapi/v1.json", "rest.openapi.json", "rest", "openapi"),
    ("openapi/workers.json", "workers.openapi.json", "workers", "openapi"),
    ("openapi/radio.json", "radio.openapi.json", "radio", "openapi"),
    ("asyncapi/listen-along.json", "listen-along.asyncapi.json", "listen-along", "asyncapi"),
    ("asyncapi/radio-chat.json", "radio-chat.asyncapi.json", "radio-chat", "asyncapi"),
]

HEADER = (
    "<!-- Generated by Scripts/update-api-docs.py from docs/api/specs. "
    "Do not edit by hand; run the script instead. -->\n\n"
)
METHODS = ("get", "post", "put", "patch", "delete")


# --------------------------------------------------------------------------
# Spec handling


def fetch(path: str) -> bytes:
    request = urllib.request.Request(BASE + path, headers={"User-Agent": "twinskaraoke-api-docs"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def canonical(data: bytes) -> str:
    return json.dumps(json.loads(data), indent=2, ensure_ascii=False, sort_keys=False) + "\n"


def resolve(spec: dict, node):
    """Follows local $refs (#/a/b/c)."""
    seen = 0
    while isinstance(node, dict) and "$ref" in node and seen < 20:
        ref = node["$ref"]
        if not ref.startswith("#/"):
            return node
        target = spec
        for part in ref[2:].split("/"):
            target = target.get(part.replace("~1", "/").replace("~0", "~"), {})
        node, seen = target, seen + 1
    return node


# --------------------------------------------------------------------------
# Compact TypeScript-like type rendering


def scalar(schema: dict) -> str:
    kind = schema.get("type")
    fmt = schema.get("format")
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if kind == "integer":
        return "int64" if fmt == "int64" else "int"
    if kind == "number":
        return "number"
    if kind == "string":
        return {"date-time": "date-time", "date": "date", "uuid": "uuid", "uri": "url",
                "binary": "binary"}.get(fmt, "string")
    if kind == "boolean":
        return "bool"
    return kind or "any"


def render(spec: dict, schema, indent: int = 0, depth: int = 0, memo: dict | None = None, name: str = "") -> str:
    """Renders a schema as a compact TypeScript-like type. Within one call tree,
    an object shape that already appeared is shown as "same as `x` above"."""
    if memo is None:
        memo = {}
    schema = resolve(spec, schema or {})
    if not isinstance(schema, dict) or not schema:
        return "any"
    pad = "  " * indent
    nullable = schema.get("nullable") or (isinstance(schema.get("type"), list) and "null" in schema["type"])
    if isinstance(schema.get("type"), list):
        schema = {**schema, "type": next((t for t in schema["type"] if t != "null"), "any")}

    for combo in ("oneOf", "anyOf"):
        if combo in schema:
            text = " | ".join(render(spec, s, indent, depth + 1, memo, name) for s in schema[combo])
            return f"({text})" + (" | null" if nullable else "")
    if "allOf" in schema:
        merged: dict = {"type": "object", "properties": {}, "required": []}
        for part in schema["allOf"]:
            part = resolve(spec, part)
            merged["properties"].update(part.get("properties", {}))
            merged["required"] += part.get("required", [])
        schema = merged

    kind = schema.get("type")
    if kind == "array" or "items" in schema:
        inner = render(spec, schema.get("items"), indent, depth + 1, memo, name)
        text = f"({inner})[]" if "|" in inner and not inner.startswith("{") else f"{inner}[]"
    elif kind == "object" or "properties" in schema:
        props = schema.get("properties") or {}
        extra = schema.get("additionalProperties")
        if not props:
            if isinstance(extra, dict):
                text = f"{{ [key: string]: {render(spec, extra, indent, depth + 1, memo, name)} }}"
            else:
                text = "object"
        elif depth > 6:
            text = "{ … }"
        elif len(props) >= 3 and json.dumps(props, sort_keys=True) in memo and depth > 0:
            text = f"{{ …same as `{memo[json.dumps(props, sort_keys=True)]}` above }}"
        else:
            if depth > 0 and len(props) >= 3:
                memo[json.dumps(props, sort_keys=True)] = name or "object"
            required = set(schema.get("required") or [])
            lines = ["{"]
            for prop_name, prop in props.items():
                prop_resolved = resolve(spec, prop)
                optional = "?" if required and prop_name not in required else ""
                comment = (prop_resolved.get("description") or "").strip().replace("\n", " ")
                rendered = render(spec, prop, indent + 1, depth + 1, memo, prop_name)
                line = f"{pad}  {prop_name}{optional}: {rendered}"
                if comment:
                    line += f"  // {comment}"
                lines.append(line)
            lines.append(pad + "}")
            text = "\n".join(lines)
    else:
        text = scalar(schema)
    return text + (" | null" if nullable and not text.endswith("| null") else "")


# --------------------------------------------------------------------------
# OpenAPI


def slug(text: str) -> str:
    """File-name slug."""
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "other"


def github_anchor(heading: str) -> str:
    """The anchor GitHub generates for a Markdown heading."""
    text = heading.strip().lower().replace("`", "")
    text = re.sub(r"[^\w\- ]", "", text)
    return text.replace(" ", "-")


def auth_text(spec: dict, op: dict) -> str:
    requirements = op.get("security", spec.get("security"))
    if not requirements:
        return "none"
    options = []
    optional = False
    for requirement in requirements:
        if not requirement:
            optional = True
        else:
            options.append(" + ".join(requirement))
    if not options:
        return "none"
    text = " or ".join(f"`{o}`" for o in options)
    return f"optional ({text})" if optional else text


def first_content(content: dict | None):
    if not content:
        return None, None
    for media in ("application/json", "text/json", "text/plain", "multipart/form-data"):
        if media in content:
            return media, content[media].get("schema")
    media, value = next(iter(content.items()))
    return media, value.get("schema")


def openapi_operations(spec: dict):
    for path, item in spec.get("paths", {}).items():
        shared = item.get("parameters", [])
        for method in METHODS:
            if method in item:
                yield method, path, item[method], shared, item.get("servers")


def operation_markdown(spec: dict, method: str, path: str, op: dict, shared: list, servers) -> str:
    out = [f"### `{method.upper()} {path}` — {op.get('summary', '').strip()}", ""]
    if servers:
        out += [f"Host: {', '.join(s['url'] for s in servers)}", ""]
    out += [f"Auth: {auth_text(spec, op)}", ""]
    if op.get("deprecated"):
        out += ["**Deprecated.**", ""]
    if op.get("description"):
        out += [op["description"].strip(), ""]

    params = [resolve(spec, p) for p in shared + op.get("parameters", [])]
    if params:
        out += ["| Parameter | In | Type | Required | Description |", "| --- | --- | --- | --- | --- |"]
        for p in params:
            description = (p.get("description") or "").strip().replace("\n", " ").replace("|", "\\|")
            kind = render(spec, p.get("schema")).replace("\n", " ").replace("|", "\\|")
            out.append(f"| `{p.get('name')}` | {p.get('in')} | `{kind}` | {'yes' if p.get('required') else 'no'} | {description} |")
        out.append("")

    body = resolve(spec, op.get("requestBody"))
    if body:
        media, schema = first_content(body.get("content"))
        required = " (required)" if body.get("required") else ""
        out += [f"Request body `{media}`{required}:", "", "```ts", render(spec, schema), "```", ""]

    responses = op.get("responses", {})
    for code, response in responses.items():
        response = resolve(spec, response)
        media, schema = first_content(response.get("content"))
        description = (response.get("description") or "").strip()
        if schema is not None:
            out += [f"Response `{code}` {description} `{media}`:", "", "```ts", render(spec, schema), "```", ""]
        else:
            out += [f"Response `{code}` {description}".rstrip(), ""]
    return "\n".join(out).rstrip() + "\n"


def write_openapi(spec: dict, slug_name: str, title_hint: str) -> list[tuple[str, str, str, str, str]]:
    """Writes one file per tag (or one file for small specs); returns index rows."""
    info = spec.get("info", {})
    by_tag: dict[str, list] = {}
    for method, path, op, shared, servers in openapi_operations(spec):
        tag = (op.get("tags") or [info.get("title", title_hint)])[0]
        by_tag.setdefault(tag, []).append((method, path, op, shared, servers))
    order = [t.get("name") for t in spec.get("tags", [])]
    tags = sorted(by_tag, key=lambda t: (order.index(t) if t in order else len(order), t))
    split = len(by_tag) > 2
    rows = []
    folder = OUT / slug_name if split else OUT
    if split:
        folder.mkdir(parents=True, exist_ok=True)
    single: list[str] = []
    for tag in tags:
        file = folder / f"{slug(tag)}.md" if split else OUT / f"{slug_name}.md"
        rel = file.relative_to(OUT).as_posix()
        tag_info = next((t for t in spec.get("tags", []) if t.get("name") == tag), {})
        section = [f"## {tag}", ""]
        if tag_info.get("description"):
            section += [tag_info["description"].strip(), ""]
        for method, path, op, shared, servers in by_tag[tag]:
            section.append(operation_markdown(spec, method, path, op, shared, servers))
            anchor = github_anchor(f"`{method.upper()} {path}` — {op.get('summary', '').strip()}")
            rows.append((tag, method.upper(), path, (op.get("summary") or "").strip(), auth_text(spec, op), f"{rel}#{anchor}"))
        if split:
            servers = ", ".join(s.get("url", "") for s in spec.get("servers", []))
            text = HEADER + f"# {info.get('title')} — {tag}\n\nBase URL: {servers}\n\n" + "\n".join(section[2:])
            file.write_text(text, encoding="utf-8")
        else:
            single += section
    if not split:
        servers = ", ".join(s.get("url", "") for s in spec.get("servers", []))
        head = f"# {info.get('title')}\n\n"
        if info.get("description"):
            head += info["description"].strip() + "\n\n"
        head += f"Base URL: {servers}\n\n"
        (OUT / f"{slug_name}.md").write_text(HEADER + head + "\n".join(single), encoding="utf-8")
    return rows


# --------------------------------------------------------------------------
# AsyncAPI


def write_asyncapi(spec: dict, slug_name: str) -> list[tuple[str, str, str, str]]:
    info = spec.get("info", {})
    out = [f"# {info.get('title')}", ""]
    if info.get("description"):
        out += [info["description"].strip(), ""]
    for name, server in spec.get("servers", {}).items():
        out += [f"Server `{name}`: `{server.get('protocol')}://{server.get('host')}{server.get('pathname', '')}`"
                + (f" — {server['description'].strip()}" if server.get("description") else ""), ""]
    for name, channel in spec.get("channels", {}).items():
        out += [f"## Channel `{channel.get('address', name)}`" + (f" — {channel['title']}" if channel.get("title") else ""), ""]
        if channel.get("description"):
            out += [channel["description"].strip(), ""]
        params = channel.get("parameters") or {}
        bindings = (channel.get("bindings") or {}).get("ws", {})
        query = resolve(spec, bindings.get("query")) if bindings.get("query") else None
        if query:
            out += ["Connection query:", "", "```ts", render(spec, query), "```", ""]
        for pname, param in params.items():
            param = resolve(spec, param)
            out.append(f"- Parameter `{pname}`: {(param.get('description') or '').strip()}")
        if params:
            out.append("")

    rows = []
    operations = spec.get("operations", {})
    for direction, heading in (("send", "Client → server (send)"), ("receive", "Server → client (receive)")):
        ops = [(k, v) for k, v in operations.items() if v.get("action") == direction]
        if not ops:
            continue
        out += [f"## {heading}", ""]
        for op_name, op in ops:
            out += [f"### {op.get('title', op_name)}", ""]
            if op.get("summary"):
                out += [op["summary"].strip(), ""]
            if op.get("description"):
                out += [op["description"].strip(), ""]
            for ref in op.get("messages", []):
                message = resolve(spec, ref)
                title = message.get("name") or message.get("title") or ref.get("$ref", "").split("/")[-1]
                summary = (message.get("summary") or "").strip()
                out += [f"#### `{title}`" + (f" — {summary}" if summary else ""), ""]
                if message.get("description"):
                    out += [message["description"].strip(), ""]
                out += ["```ts", render(spec, message.get("payload")), "```", ""]
                rows.append((direction, title, summary, f"{slug_name}.md"))
    (OUT / f"{slug_name}.md").write_text(HEADER + "\n".join(out).rstrip() + "\n", encoding="utf-8")
    return rows


